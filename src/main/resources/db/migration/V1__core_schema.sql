create or replace view vw_mc_bed_occupancy as
select u.code unit_code, b.code bed_code, b.status bed_status, a.admission_id, p.public_id patient_public_id,
       o.started_at, systimestamp - o.started_at occupied_duration
  from mc_bed b
  join mc_business_unit u on u.unit_id = b.unit_id
  left join mc_bed_occupancy o on o.bed_id = b.bed_id and o.ended_at is null
  left join mc_admission a on a.admission_id = o.admission_id
  left join mc_patient p on p.patient_id = a.patient_id;

create or replace view vw_mc_financial_aging as
select unit_id, title_type,
       case when due_date >= trunc(sysdate) then 'CURRENT'
            when trunc(sysdate) - due_date <= 30 then '1_30'
            when trunc(sysdate) - due_date <= 60 then '31_60'
            when trunc(sysdate) - due_date <= 90 then '61_90' else 'OVER_90' end aging_bucket,
       count(*) title_count, sum(open_amount) open_amount
  from mc_financial_title
 where status in ('OPEN','PARTIAL')
 group by unit_id, title_type,
       case when due_date >= trunc(sysdate) then 'CURRENT'
            when trunc(sysdate) - due_date <= 30 then '1_30'
            when trunc(sysdate) - due_date <= 60 then '31_60'
            when trunc(sysdate) - due_date <= 90 then '61_90' else 'OVER_90' end;

create or replace view vw_mc_trial_balance as
select a.code account_code, a.name account_name, trunc(e.entry_date, 'MM') competence,
       sum(e.debit_amount) debit_amount, sum(e.credit_amount) credit_amount,
       sum(e.debit_amount - e.credit_amount) balance
  from mc_journal_entry e
  join mc_journal_batch b on b.batch_id = e.batch_id and b.status = 'POSTED'
  join mc_account a on a.account_id = e.account_id
 group by a.code, a.name, trunc(e.entry_date, 'MM');
