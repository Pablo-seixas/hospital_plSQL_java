create table mc_business_unit (
    unit_id number(19) generated by default as identity primary key,
    code varchar2(30) not null unique,
    name varchar2(150) not null,
    active char(1) default 'Y' not null check (active in ('Y','N')),
    created_at timestamp default systimestamp not null
);

create table mc_cost_center (
    cost_center_id number(19) generated by default as identity primary key,
    unit_id number(19) not null references mc_business_unit(unit_id),
    code varchar2(30) not null,
    name varchar2(150) not null,
    active char(1) default 'Y' not null check (active in ('Y','N')),
    constraint uk_mc_cost_center unique (unit_id, code)
);

create table mc_patient (
    patient_id number(19) generated by default as identity primary key,
    public_id raw(16) default sys_guid() not null unique,
    synthetic_name varchar2(180) not null,
    birth_date date not null,
    record_version number(10) default 0 not null,
    created_at timestamp default systimestamp not null
);

create table mc_bed (
    bed_id number(19) generated by default as identity primary key,
    unit_id number(19) not null references mc_business_unit(unit_id),
    code varchar2(30) not null,
    status varchar2(20) default 'AVAILABLE' not null check (status in ('AVAILABLE','OCCUPIED','CLEANING','BLOCKED','MAINTENANCE')),
    record_version number(10) default 0 not null,
    constraint uk_mc_bed unique (unit_id, code)
);

create table mc_admission (
    admission_id number(19) generated by default as identity primary key,
    patient_id number(19) not null references mc_patient(patient_id),
    unit_id number(19) not null references mc_business_unit(unit_id),
    current_bed_id number(19) references mc_bed(bed_id),
    status varchar2(20) default 'ACTIVE' not null check (status in ('ACTIVE','DISCHARGED','CANCELLED')),
    admitted_at timestamp default systimestamp not null,
    discharged_at timestamp,
    constraint ck_mc_admission_dates check (discharged_at is null or discharged_at >= admitted_at)
);

create unique index uk_mc_active_bed on mc_admission (case when status = 'ACTIVE' then current_bed_id end);
create unique index uk_mc_active_patient on mc_admission (case when status = 'ACTIVE' then patient_id end);

create table mc_bed_occupancy (
    occupancy_id number(19) generated by default as identity primary key,
    admission_id number(19) not null references mc_admission(admission_id),
    bed_id number(19) not null references mc_bed(bed_id),
    started_at timestamp default systimestamp not null,
    ended_at timestamp,
    transfer_reason varchar2(300),
    constraint ck_mc_occupancy_dates check (ended_at is null or ended_at >= started_at)
);

create unique index uk_mc_open_bed_occupancy on mc_bed_occupancy (case when ended_at is null then bed_id end);

create table mc_product (
    product_id number(19) generated by default as identity primary key,
    sku varchar2(40) not null unique,
    name varchar2(180) not null,
    product_type varchar2(20) not null check (product_type in ('MEDICATION','MATERIAL')),
    allow_negative char(1) default 'N' not null check (allow_negative in ('Y','N'))
);

create table mc_inventory_lot (
    lot_id number(19) generated by default as identity primary key,
    product_id number(19) not null references mc_product(product_id),
    unit_id number(19) not null references mc_business_unit(unit_id),
    lot_code varchar2(60) not null,
    expires_on date,
    quantity number(18,4) default 0 not null check (quantity >= 0),
    reserved_quantity number(18,4) default 0 not null,
    record_version number(10) default 0 not null,
    constraint ck_mc_inventory_lot_reserved check (reserved_quantity >= 0 and reserved_quantity <= quantity),
    constraint uk_mc_inventory_lot unique (product_id, unit_id, lot_code)
);

create index ix_mc_lot_fefo on mc_inventory_lot(product_id, unit_id, expires_on, lot_id);

create table mc_inventory_movement (
    movement_id number(19) generated by default as identity primary key,
    lot_id number(19) not null references mc_inventory_lot(lot_id),
    movement_type varchar2(20) not null check (movement_type in ('ENTRY','ISSUE','RESERVE','RELEASE','ADJUST','LOSS','TRANSFER')),
    quantity number(18,4) not null check (quantity > 0),
    reference_type varchar2(40),
    reference_id varchar2(80),
    correlation_id varchar2(64) not null,
    occurred_at timestamp default systimestamp not null,
    actor varchar2(120) not null,
    constraint uk_mc_inventory_idem unique (correlation_id, movement_type, lot_id)
);

create table mc_account (
    account_id number(19) generated by default as identity primary key,
    parent_account_id number(19) references mc_account(account_id),
    code varchar2(40) not null unique,
    name varchar2(180) not null,
    nature char(1) not null check (nature in ('D','C')),
    posting_allowed char(1) default 'Y' not null check (posting_allowed in ('Y','N')),
    active char(1) default 'Y' not null check (active in ('Y','N'))
);

create table mc_accounting_period (
    period_id number(19) generated by default as identity primary key,
    fiscal_year number(4) not null,
    fiscal_month number(2) not null check (fiscal_month between 1 and 12),
    status varchar2(20) default 'OPEN' not null check (status in ('OPEN','CLOSING','CLOSED')),
    closed_at timestamp,
    closed_by varchar2(120),
    constraint uk_mc_period unique (fiscal_year, fiscal_month)
);

create table mc_journal_batch (
    batch_id number(19) generated by default as identity primary key,
    period_id number(19) not null references mc_accounting_period(period_id),
    source_type varchar2(30) not null,
    source_id varchar2(80) not null,
    idempotency_key varchar2(100) not null unique,
    status varchar2(20) default 'DRAFT' not null check (status in ('DRAFT','POSTED','REVERSED')),
    posted_at timestamp,
    reversal_batch_id number(19) references mc_journal_batch(batch_id)
);

create table mc_journal_entry (
    entry_id number(19) generated by default as identity primary key,
    batch_id number(19) not null references mc_journal_batch(batch_id) on delete cascade,
    account_id number(19) not null references mc_account(account_id),
    cost_center_id number(19) references mc_cost_center(cost_center_id),
    entry_date date not null,
    description varchar2(300) not null,
    debit_amount number(18,2) default 0 not null check (debit_amount >= 0),
    credit_amount number(18,2) default 0 not null check (credit_amount >= 0),
    constraint ck_mc_entry_side check ((debit_amount > 0 and credit_amount = 0) or (credit_amount > 0 and debit_amount = 0))
);

create index ix_mc_entry_reporting on mc_journal_entry(account_id, entry_date, cost_center_id);

create table mc_financial_title (
    title_id number(19) generated by default as identity primary key,
    title_type varchar2(10) not null check (title_type in ('PAYABLE','RECEIVABLE')),
    unit_id number(19) not null references mc_business_unit(unit_id),
    cost_center_id number(19) references mc_cost_center(cost_center_id),
    external_reference varchar2(100),
    idempotency_key varchar2(100) not null unique,
    issue_date date not null,
    due_date date not null,
    original_amount number(18,2) not null check (original_amount > 0),
    open_amount number(18,2) not null check (open_amount >= 0),
    status varchar2(20) default 'OPEN' not null check (status in ('OPEN','PARTIAL','SETTLED','CANCELLED','REVERSED')),
    record_version number(10) default 0 not null,
    constraint ck_mc_title_dates check (due_date >= issue_date)
);

create index ix_mc_title_aging on mc_financial_title(unit_id, status, due_date, title_type);

create table mc_settlement (
    settlement_id number(19) generated by default as identity primary key,
    title_id number(19) not null references mc_financial_title(title_id),
    idempotency_key varchar2(100) not null unique,
    settled_at timestamp default systimestamp not null,
    principal_amount number(18,2) not null,
    interest_amount number(18,2) default 0 not null,
    penalty_amount number(18,2) default 0 not null,
    discount_amount number(18,2) default 0 not null,
    status varchar2(20) default 'CONFIRMED' not null check (status in ('CONFIRMED','REVERSED')),
    reversal_id number(19) references mc_settlement(settlement_id)
);

