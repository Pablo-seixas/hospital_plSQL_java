create or replace package pkg_billing as
    procedure close_account(p_hospital_account_id number, p_actor varchar2, p_correlation_id varchar2);
    procedure invoice_batch(p_invoice_batch_id number, p_actor varchar2, p_correlation_id varchar2, p_processed out number);
    procedure register_denial(p_invoice_id number, p_item_id number, p_reason_code varchar2, p_reason varchar2, p_amount number, p_actor varchar2, p_correlation_id varchar2);
end pkg_billing;
/

create or replace package body pkg_billing as
    procedure close_account(p_hospital_account_id number, p_actor varchar2, p_correlation_id varchar2) is
        v_invalid number;
        v_total number;
        v_status mc_hospital_account.status%type;
    begin
        select status into v_status from mc_hospital_account where hospital_account_id = p_hospital_account_id for update;
        if v_status <> 'OPEN' then raise_application_error(-20501, 'ACCOUNT_NOT_OPEN'); end if;
        select count(*), nvl(sum(total_amount),0) into v_invalid, v_total from mc_billable_item where hospital_account_id = p_hospital_account_id and status <> 'VALID';
        if v_invalid > 0 then raise_application_error(-20502, 'ACCOUNT_HAS_INVALID_ITEMS'); end if;
        if v_total <= 0 then raise_application_error(-20503, 'ACCOUNT_WITHOUT_CHARGES'); end if;
        update mc_hospital_account set status = 'CLOSED', closed_at = systimestamp, gross_amount = v_total, record_version = record_version + 1 where hospital_account_id = p_hospital_account_id;
        pkg_audit.record_event(p_actor, 'HOSPITAL_ACCOUNT_CLOSED', 'HOSPITAL_ACCOUNT', to_char(p_hospital_account_id), p_correlation_id);
    end;

    procedure invoice_batch(p_invoice_batch_id number, p_actor varchar2, p_correlation_id varchar2, p_processed out number) is
        type t_account_ids is table of mc_hospital_account.hospital_account_id%type;
        type t_amounts is table of mc_hospital_account.net_amount%type;
        v_ids t_account_ids;
        v_amounts t_amounts;
        v_unit_id number;
    begin
        select unit_id into v_unit_id from mc_invoice_batch where invoice_batch_id = p_invoice_batch_id and status = 'OPEN' for update;
        update mc_invoice_batch set status = 'PROCESSING' where invoice_batch_id = p_invoice_batch_id;
        select h.hospital_account_id, h.net_amount bulk collect into v_ids, v_amounts
          from mc_hospital_account h join mc_admission a on a.admission_id = h.admission_id
         where h.status = 'CLOSED' and a.unit_id = v_unit_id;
        forall i in indices of v_ids save exceptions
            insert into mc_invoice(invoice_batch_id, hospital_account_id, invoice_number, amount)
            values (p_invoice_batch_id, v_ids(i), 'INV-' || p_invoice_batch_id || '-' || v_ids(i), v_amounts(i));
        forall i in indices of v_ids
            update mc_hospital_account set status = 'INVOICED' where hospital_account_id = v_ids(i);
        p_processed := v_ids.count;
        update mc_invoice_batch set status = 'CLOSED', closed_at = systimestamp where invoice_batch_id = p_invoice_batch_id;
        pkg_audit.record_event(p_actor, 'INVOICE_BATCH_CLOSED', 'INVOICE_BATCH', to_char(p_invoice_batch_id), p_correlation_id);
    exception
        when no_data_found then raise_application_error(-20504, 'BATCH_NOT_OPEN');
        when others then
            update mc_invoice_batch set status = 'ERROR' where invoice_batch_id = p_invoice_batch_id;
            raise;
    end;

    procedure register_denial(p_invoice_id number, p_item_id number, p_reason_code varchar2, p_reason varchar2, p_amount number, p_actor varchar2, p_correlation_id varchar2) is
        v_invoice_amount number;
    begin
        select amount into v_invoice_amount from mc_invoice where invoice_id = p_invoice_id for update;
        if p_amount <= 0 or p_amount > v_invoice_amount then raise_application_error(-20505, 'INVALID_DENIAL_AMOUNT'); end if;
        insert into mc_denial(invoice_id, billable_item_id, reason_code, reason_description, denied_amount) values (p_invoice_id, p_item_id, p_reason_code, p_reason, p_amount);
        update mc_invoice set status = 'PARTIAL' where invoice_id = p_invoice_id;
        pkg_audit.record_event(p_actor, 'DENIAL_REGISTERED', 'INVOICE', to_char(p_invoice_id), p_correlation_id);
    end;
end pkg_billing;
/

create or replace package pkg_reporting as
    function expiring_lots(p_days number default 60) return tt_expiry_alert pipelined;
    procedure open_report(p_report_name varchar2, p_unit_id number, p_result out sys_refcursor);
    procedure refresh_analytics;
end pkg_reporting;
/

create or replace package body pkg_reporting as
    function expiring_lots(p_days number default 60) return tt_expiry_alert pipelined is
    begin
        for r in (select product_id, unit_id, lot_id, lot_code, expires_on, quantity from mc_inventory_lot where expires_on between trunc(sysdate) and trunc(sysdate) + p_days and quantity > 0 order by expires_on) loop
            pipe row(ty_expiry_alert(r.product_id, r.unit_id, r.lot_id, r.lot_code, r.expires_on, r.quantity));
        end loop;
        return;
    end;

    procedure open_report(p_report_name varchar2, p_unit_id number, p_result out sys_refcursor) is
        v_sql varchar2(4000);
    begin
        if p_report_name = 'FINANCIAL_AGING' then
            v_sql := 'select title_type, aging_bucket, title_count, open_amount from vw_mc_financial_aging where unit_id = :unit_id order by title_type, aging_bucket';
        elsif p_report_name = 'BED_OCCUPANCY' then
            v_sql := 'select unit_code, bed_code, bed_status, admission_id, started_at from vw_mc_bed_occupancy where unit_code = (select code from mc_business_unit where unit_id = :unit_id) order by bed_code';
        else
            raise_application_error(-20601, 'REPORT_NOT_ALLOWED');
        end if;
        open p_result for v_sql using p_unit_id;
    end;

    procedure refresh_analytics is
    begin
        null;
    end;
end pkg_reporting;
/

create or replace view vw_mc_billing_summary as
select a.unit_id, trunc(i.issued_at, 'MM') competence,
       count(*) invoice_count, sum(i.amount) invoiced_amount,
       sum(nvl(d.denied_amount,0)) denied_amount,
       sum(i.amount - nvl(d.denied_amount,0)) recoverable_amount
  from mc_invoice i
  join mc_hospital_account h on h.hospital_account_id = i.hospital_account_id
  join mc_admission a on a.admission_id = h.admission_id
  left join (select invoice_id, sum(denied_amount) denied_amount from mc_denial group by invoice_id) d on d.invoice_id = i.invoice_id
 group by a.unit_id, trunc(i.issued_at, 'MM');

create materialized view mv_mc_executive_kpi
build immediate refresh complete on demand as
select u.unit_id, u.code unit_code,
       nvl(a.active_admissions, 0) active_admissions,
       nvl(b.available_beds, 0) available_beds,
       nvl(f.receivables, 0) receivables,
       nvl(f.payables, 0) payables
  from mc_business_unit u
  left join (select unit_id, count(*) active_admissions from mc_admission where status = 'ACTIVE' group by unit_id) a on a.unit_id = u.unit_id
  left join (select unit_id, count(*) available_beds from mc_bed where status = 'AVAILABLE' group by unit_id) b on b.unit_id = u.unit_id
  left join (select unit_id,
                    sum(case when title_type = 'RECEIVABLE' then open_amount else 0 end) receivables,
                    sum(case when title_type = 'PAYABLE' then open_amount else 0 end) payables
               from mc_financial_title
              where status in ('OPEN','PARTIAL')
              group by unit_id) f on f.unit_id = u.unit_id
 where u.active = 'Y';

begin
    dbms_scheduler.create_job(
        job_name => 'JOB_MC_REFRESH_ANALYTICS',
        job_type => 'PLSQL_BLOCK',
        job_action => 'begin dbms_mview.refresh(''MV_MC_EXECUTIVE_KPI'', ''C''); end;',
        start_date => systimestamp,
        repeat_interval => 'FREQ=HOURLY;INTERVAL=1',
        enabled => true,
        auto_drop => false);
exception
    when others then
        if sqlcode <> -27477 then raise; end if;
end;
/
