create table mc_hospital_account (
    hospital_account_id number(19) generated by default as identity primary key,
    admission_id number(19) not null references mc_admission(admission_id),
    account_number varchar2(40) not null unique,
    status varchar2(20) default 'OPEN' not null check (status in ('OPEN','VALIDATING','CLOSED','INVOICED','CANCELLED')),
    opened_at timestamp default systimestamp not null,
    closed_at timestamp,
    gross_amount number(18,2) default 0 not null,
    denied_amount number(18,2) default 0 not null,
    net_amount generated always as (gross_amount - denied_amount) virtual,
    record_version number(10) default 0 not null
);

create table mc_billable_item (
    billable_item_id number(19) generated by default as identity primary key,
    hospital_account_id number(19) not null references mc_hospital_account(hospital_account_id),
    item_type varchar2(20) not null check (item_type in ('DAILY_RATE','FEE','MATERIAL','MEDICATION','PROCEDURE')),
    item_code varchar2(40) not null,
    description varchar2(180) not null,
    service_date timestamp not null,
    quantity number(14,4) not null check (quantity > 0),
    unit_price number(18,4) not null check (unit_price >= 0),
    total_amount generated always as (round(quantity * unit_price, 2)) virtual,
    status varchar2(20) default 'PENDING' not null check (status in ('PENDING','VALID','INCONSISTENT','DENIED')),
    idempotency_key varchar2(100) not null unique
);

create index ix_mc_billable_account on mc_billable_item(hospital_account_id, status, service_date);

create table mc_invoice_batch (
    invoice_batch_id number(19) generated by default as identity primary key,
    unit_id number(19) not null references mc_business_unit(unit_id),
    competence_date date not null,
    status varchar2(20) default 'OPEN' not null check (status in ('OPEN','PROCESSING','CLOSED','ERROR')),
    created_at timestamp default systimestamp not null,
    closed_at timestamp,
    constraint uk_mc_invoice_batch unique (unit_id, competence_date)
);

create table mc_invoice (
    invoice_id number(19) generated by default as identity primary key,
    invoice_batch_id number(19) not null references mc_invoice_batch(invoice_batch_id),
    hospital_account_id number(19) not null unique references mc_hospital_account(hospital_account_id),
    invoice_number varchar2(50) not null unique,
    amount number(18,2) not null check (amount > 0),
    status varchar2(20) default 'ISSUED' not null check (status in ('ISSUED','SUBMITTED','PARTIAL','SETTLED','CANCELLED')),
    issued_at timestamp default systimestamp not null
);

create table mc_denial (
    denial_id number(19) generated by default as identity primary key,
    invoice_id number(19) not null references mc_invoice(invoice_id),
    billable_item_id number(19) references mc_billable_item(billable_item_id),
    reason_code varchar2(40) not null,
    reason_description varchar2(300) not null,
    denied_amount number(18,2) not null check (denied_amount > 0),
    status varchar2(20) default 'OPEN' not null check (status in ('OPEN','APPEALED','ACCEPTED','RECOVERED')),
    created_at timestamp default systimestamp not null
);

create table mc_denial_appeal (
    appeal_id number(19) generated by default as identity primary key,
    denial_id number(19) not null references mc_denial(denial_id),
    protocol varchar2(60) not null unique,
    justification varchar2(1000) not null,
    appealed_amount number(18,2) not null check (appealed_amount > 0),
    status varchar2(20) default 'SUBMITTED' not null check (status in ('SUBMITTED','ACCEPTED','REJECTED')),
    submitted_at timestamp default systimestamp not null
);

create table mc_bank_statement_line (
    statement_line_id number(19) generated by default as identity primary key,
    bank_account_code varchar2(40) not null,
    external_id varchar2(100) not null,
    transaction_date date not null,
    amount number(18,2) not null,
    description varchar2(300),
    reconciliation_status varchar2(20) default 'PENDING' not null check (reconciliation_status in ('PENDING','MATCHED','DIVERGENT','IGNORED')),
    settlement_id number(19) references mc_settlement(settlement_id),
    constraint uk_mc_statement_line unique (bank_account_code, external_id)
);

