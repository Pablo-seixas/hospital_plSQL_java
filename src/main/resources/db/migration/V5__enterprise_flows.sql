create table mc_party (
    party_id number(19) generated by default as identity primary key,
    party_type varchar2(20) not null check (party_type in ('SUPPLIER','PAYER','OTHER')),
    code varchar2(40) not null unique,
    legal_name varchar2(180) not null,
    active char(1) default 'Y' not null check (active in ('Y','N'))
);

create table mc_bank_account (
    bank_account_id number(19) generated by default as identity primary key,
    unit_id number(19) not null references mc_business_unit(unit_id),
    code varchar2(40) not null unique,
    bank_name varchar2(120) not null,
    active char(1) default 'Y' not null check (active in ('Y','N'))
);

create table mc_financial_period (
    period_id number(19) generated by default as identity primary key,
    fiscal_year number(4) not null,
    fiscal_month number(2) not null check (fiscal_month between 1 and 12),
    status varchar2(20) default 'OPEN' not null check (status in ('OPEN','CLOSED')),
    closed_at timestamp,
    closed_by varchar2(120),
    constraint uk_mc_financial_period unique (fiscal_year, fiscal_month)
);

