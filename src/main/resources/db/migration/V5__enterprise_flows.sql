    allocation_percent number(9,6) not null check (allocation_percent > 0 and allocation_percent <= 100),
    allocation_amount number(18,2) not null check (allocation_amount > 0)
);

create table mc_financial_movement (
    movement_id number(19) generated by default as identity primary key,
    title_id number(19) not null references mc_financial_title(title_id),
    settlement_id number(19) references mc_settlement(settlement_id),
    bank_account_id number(19) references mc_bank_account(bank_account_id),
    movement_type varchar2(20) not null check (movement_type in ('PAYMENT','RECEIPT','REVERSAL','ADJUSTMENT')),
    amount number(18,2) not null check (amount > 0),
    occurred_at timestamp default systimestamp not null,
    idempotency_key varchar2(100) not null unique
