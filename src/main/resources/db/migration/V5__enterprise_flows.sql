create or replace package pkg_integration as
    procedure enqueue_accounting(p_source_type varchar2, p_source_id varchar2, p_event_type varchar2, p_amount number, p_competence date, p_debit_account_id number, p_credit_account_id number, p_cost_center_id number, p_idempotency_key varchar2);
    procedure process_pending(p_limit number, p_actor varchar2, p_processed out number, p_failed out number);
    procedure reprocess_error(p_integration_id number, p_actor varchar2);
end pkg_integration;
/

create or replace package body pkg_integration as
    procedure enqueue_accounting(p_source_type varchar2, p_source_id varchar2, p_event_type varchar2, p_amount number, p_competence date, p_debit_account_id number, p_credit_account_id number, p_cost_center_id number, p_idempotency_key varchar2) is
    begin
        insert into mc_accounting_integration(source_type, source_id, event_type, event_amount, competence_date, debit_account_id, credit_account_id, cost_center_id, idempotency_key)
        values (p_source_type, p_source_id, p_event_type, p_amount, p_competence, p_debit_account_id, p_credit_account_id, p_cost_center_id, p_idempotency_key);
    exception
        when dup_val_on_index then null;
    end;

    procedure process_pending(p_limit number, p_actor varchar2, p_processed out number, p_failed out number) is
        v_period_id number;
        v_batch_id number;
        v_count number := 0;
    begin
        p_processed := 0;
        p_failed := 0;
        for r in (select * from mc_accounting_integration where status in ('PENDING','ERROR') and retry_count < 5 order by created_at fetch first p_limit rows only for update skip locked) loop
            savepoint before_integration_item;
            begin
                update mc_accounting_integration set status = 'PROCESSING', retry_count = retry_count + 1 where integration_id = r.integration_id;
                select period_id into v_period_id from mc_accounting_period where fiscal_year = extract(year from r.competence_date) and fiscal_month = extract(month from r.competence_date) and status = 'OPEN';
                insert into mc_journal_batch(period_id, source_type, source_id, idempotency_key)
                values (v_period_id, r.source_type, r.source_id, 'INT-' || r.integration_id) returning batch_id into v_batch_id;
                insert all
                    into mc_journal_entry(batch_id, account_id, cost_center_id, entry_date, description, debit_amount, credit_amount) values (v_batch_id, r.debit_account_id, r.cost_center_id, r.competence_date, r.event_type, r.event_amount, 0)
                    into mc_journal_entry(batch_id, account_id, cost_center_id, entry_date, description, debit_amount, credit_amount) values (v_batch_id, r.credit_account_id, r.cost_center_id, r.competence_date, r.event_type, 0, r.event_amount)
                select 1 from dual;
                pkg_accounting.post_batch(v_batch_id, p_actor, 'INT-' || r.integration_id);
                update mc_accounting_integration set status = 'PROCESSED', batch_id = v_batch_id, processed_at = systimestamp, last_error_code = null, last_error_message = null where integration_id = r.integration_id;
                p_processed := p_processed + 1;
            exception
                when others then
                    rollback to before_integration_item;
                    update mc_accounting_integration set status = 'ERROR', retry_count = retry_count + 1, last_error_code = to_char(sqlcode), last_error_message = substr(sqlerrm, 1, 500) where integration_id = r.integration_id;
                    p_failed := p_failed + 1;
            end;
            v_count := v_count + 1;
        end loop;
    end;

    procedure reprocess_error(p_integration_id number, p_actor varchar2) is
    begin
        update mc_accounting_integration set status = 'PENDING', last_error_code = null, last_error_message = null where integration_id = p_integration_id and status = 'ERROR' and retry_count < 5;
        if sql%rowcount <> 1 then raise_application_error(-20701, 'INTEGRATION_NOT_REPROCESSABLE'); end if;
        pkg_audit.record_event(p_actor, 'INTEGRATION_REQUEUED', 'ACCOUNTING_INTEGRATION', to_char(p_integration_id), 'REPROCESS-' || p_integration_id);
    end;
end pkg_integration;
/

create or replace package pkg_inventory_reservation as
    procedure reserve_fefo(p_product_id number, p_unit_id number, p_quantity number, p_reference_type varchar2, p_reference_id varchar2, p_idempotency_key varchar2, p_reservation_id out number);
    procedure cancel_reservation(p_reservation_id number, p_actor varchar2, p_correlation_id varchar2);
end pkg_inventory_reservation;
/

create or replace package body pkg_inventory_reservation as
    procedure reserve_fefo(p_product_id number, p_unit_id number, p_quantity number, p_reference_type varchar2, p_reference_id varchar2, p_idempotency_key varchar2, p_reservation_id out number) is
        v_remaining number := p_quantity;
        v_take number;
    begin
        if p_quantity <= 0 then raise_application_error(-20201, 'INVALID_RESERVATION_QUANTITY'); end if;
        begin
            insert into mc_stock_reservation(product_id, unit_id, requested_quantity, reference_type, reference_id, idempotency_key)
            values (p_product_id, p_unit_id, p_quantity, p_reference_type, p_reference_id, p_idempotency_key) returning reservation_id into p_reservation_id;
        exception when dup_val_on_index then
            select reservation_id into p_reservation_id from mc_stock_reservation where idempotency_key = p_idempotency_key;
            return;
        end;
        savepoint before_reservation_lots;
        for lot in (select lot_id, quantity - reserved_quantity available from mc_inventory_lot where product_id = p_product_id and unit_id = p_unit_id and quantity > reserved_quantity and (expires_on is null or expires_on >= trunc(sysdate)) order by expires_on nulls last, lot_id for update skip locked) loop
            exit when v_remaining = 0;
            v_take := least(lot.available, v_remaining);
            update mc_inventory_lot set reserved_quantity = reserved_quantity + v_take, record_version = record_version + 1 where lot_id = lot.lot_id;
            insert into mc_stock_reservation_lot(reservation_id, lot_id, quantity) values (p_reservation_id, lot.lot_id, v_take);
            v_remaining := v_remaining - v_take;
        end loop;
        if v_remaining > 0 then rollback to before_reservation_lots; delete from mc_stock_reservation where reservation_id = p_reservation_id; raise_application_error(-20202, 'INSUFFICIENT_STOCK'); end if;
    end;

    procedure cancel_reservation(p_reservation_id number, p_actor varchar2, p_correlation_id varchar2) is
    begin
        for r in (select lot_id, quantity from mc_stock_reservation_lot where reservation_id = p_reservation_id order by lot_id for update) loop
            update mc_inventory_lot set reserved_quantity = reserved_quantity - r.quantity, record_version = record_version + 1 where lot_id = r.lot_id;
        end loop;
        update mc_stock_reservation set status = 'CANCELLED' where reservation_id = p_reservation_id and status = 'ACTIVE';
        if sql%rowcount <> 1 then raise_application_error(-20204, 'RESERVATION_NOT_ACTIVE'); end if;
        pkg_audit.record_event(p_actor, 'STOCK_RESERVATION_CANCELLED', 'STOCK_RESERVATION', to_char(p_reservation_id), p_correlation_id);
    end;
end pkg_inventory_reservation;
/

create or replace view vw_mc_integration_trace as
select i.integration_id, i.source_type, i.source_id, i.event_type, i.status integration_status,
       i.event_amount, i.created_at, i.processed_at, b.batch_id, b.status batch_status,
       count(e.entry_id) entry_count, nvl(sum(e.debit_amount),0) debit_amount, nvl(sum(e.credit_amount),0) credit_amount
  from mc_accounting_integration i
  left join mc_journal_batch b on b.batch_id = i.batch_id
  left join mc_journal_entry e on e.batch_id = b.batch_id
 group by i.integration_id, i.source_type, i.source_id, i.event_type, i.status, i.event_amount, i.created_at, i.processed_at, b.batch_id, b.status;

