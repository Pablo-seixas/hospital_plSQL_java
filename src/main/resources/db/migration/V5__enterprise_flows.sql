create table mc_accounting_integration (
    integration_id number(19) generated by default as identity primary key,
    source_type varchar2(30) not null,
    source_id varchar2(80) not null,
    event_type varchar2(30) not null,
    event_amount number(18,2) not null,
    competence_date date not null,
    debit_account_id number(19) not null references mc_account(account_id),
    credit_account_id number(19) not null references mc_account(account_id),
    cost_center_id number(19) references mc_cost_center(cost_center_id),
    status varchar2(20) default 'PENDING' not null check (status in ('PENDING','PROCESSING','PROCESSED','ERROR','REVERSED')),
    idempotency_key varchar2(100) not null unique,
    batch_id number(19) references mc_journal_batch(batch_id),
    retry_count number(5) default 0 not null,
    last_error_code varchar2(40),
    last_error_message varchar2(500),
    created_at timestamp default systimestamp not null,
    processed_at timestamp
);

create index ix_mc_accounting_integration_queue on mc_accounting_integration(status, created_at, integration_id);

