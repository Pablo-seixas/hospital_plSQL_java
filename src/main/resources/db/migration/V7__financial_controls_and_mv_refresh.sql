alter table mc_settlement add constraint ck_mc_settlement_amounts check (
    principal_amount > 0 and interest_amount >= 0 and penalty_amount >= 0 and discount_amount >= 0
    and discount_amount <= principal_amount + interest_amount + penalty_amount
);

create table mc_analytics_refresh_log (
    refresh_id number(19) generated by default as identity primary key,
    materialized_view_name varchar2(128) not null,
    started_at timestamp not null,
    finished_at timestamp,
    status varchar2(20) not null check (status in ('RUNNING','SUCCESS','ERROR')),
    refreshed_by varchar2(120) not null,
    error_code number,
    error_message varchar2(500),
    row_count number(19)
);

create index ix_mc_analytics_refresh_log on mc_analytics_refresh_log(materialized_view_name, started_at desc);

create or replace package pkg_financial as
    procedure create_title(p_type varchar2, p_unit_id number, p_cost_center_id number, p_reference varchar2, p_idempotency_key varchar2, p_issue_date date, p_due_date date, p_amount number, p_title_id out number);
    procedure settle_title(p_title_id number, p_idempotency_key varchar2, p_principal number, p_interest number, p_penalty number, p_discount number, p_actor varchar2, p_correlation_id varchar2);
    procedure cancel_title(p_title_id number, p_reason varchar2, p_actor varchar2, p_correlation_id varchar2);
    procedure reverse_settlement(p_settlement_id number, p_idempotency_key varchar2, p_actor varchar2, p_correlation_id varchar2, p_reversal_id out number);
end pkg_financial;
/

create or replace package body pkg_financial as
    procedure assert_open_period(p_date date) is
        v_status mc_accounting_period.status%type;
    begin
        select status into v_status
          from mc_accounting_period
         where fiscal_year = extract(year from p_date)
           and fiscal_month = extract(month from p_date);
        if v_status <> 'OPEN' then raise_application_error(-20404, 'FINANCIAL_PERIOD_CLOSED'); end if;
    exception
        when no_data_found then raise_application_error(-20404, 'FINANCIAL_PERIOD_NOT_OPEN');
    end;

    procedure create_title(p_type varchar2, p_unit_id number, p_cost_center_id number, p_reference varchar2, p_idempotency_key varchar2, p_issue_date date, p_due_date date, p_amount number, p_title_id out number) is
        v_existing mc_financial_title%rowtype;
    begin
        if p_type not in ('PAYABLE','RECEIVABLE') or p_idempotency_key is null or p_issue_date is null or p_due_date is null or p_due_date < p_issue_date or p_amount is null or p_amount <= 0 then
            raise_application_error(-20405, 'INVALID_FINANCIAL_TITLE');
        end if;
        assert_open_period(p_issue_date);
        begin
            insert into mc_financial_title(title_type, unit_id, cost_center_id, external_reference, idempotency_key, issue_date, due_date, original_amount, open_amount)
            values (p_type, p_unit_id, p_cost_center_id, p_reference, p_idempotency_key, p_issue_date, p_due_date, p_amount, p_amount)
            returning title_id into p_title_id;
        exception
            when dup_val_on_index then
                select * into v_existing from mc_financial_title where idempotency_key = p_idempotency_key;
                if v_existing.title_type <> p_type or v_existing.unit_id <> p_unit_id
                   or (v_existing.cost_center_id <> p_cost_center_id or (v_existing.cost_center_id is null and p_cost_center_id is not null) or (v_existing.cost_center_id is not null and p_cost_center_id is null))
                   or (v_existing.external_reference <> p_reference or (v_existing.external_reference is null and p_reference is not null) or (v_existing.external_reference is not null and p_reference is null))
                   or v_existing.issue_date <> p_issue_date or v_existing.due_date <> p_due_date
                   or v_existing.original_amount <> p_amount then
                    raise_application_error(-20406, 'IDEMPOTENCY_PAYLOAD_MISMATCH');
                end if;
                p_title_id := v_existing.title_id;
        end;
        pkg_audit.record_event(p_actor => 'SYSTEM', p_action => 'TITLE_CREATED', p_entity_type => 'FINANCIAL_TITLE', p_entity_id => to_char(p_title_id), p_correlation_id => p_idempotency_key);
    end;

    procedure settle_title(p_title_id number, p_idempotency_key varchar2, p_principal number, p_interest number, p_penalty number, p_discount number, p_actor varchar2, p_correlation_id varchar2) is
        v_open number;
        v_status mc_financial_title.status%type;
        v_settlement_id number;
        e_resource_busy exception;
        e_wait_timeout exception;
        pragma exception_init(e_resource_busy, -54);
        pragma exception_init(e_wait_timeout, -30006);
    begin
        if p_idempotency_key is null or p_principal is null or p_principal <= 0 or nvl(p_interest, 0) < 0 or nvl(p_penalty, 0) < 0 or nvl(p_discount, 0) < 0 or nvl(p_discount, 0) > p_principal + nvl(p_interest, 0) + nvl(p_penalty, 0) then
            raise_application_error(-20402, 'INVALID_SETTLEMENT_AMOUNT');
        end if;
        assert_open_period(trunc(sysdate));
        select open_amount, status into v_open, v_status from mc_financial_title where title_id = p_title_id for update wait 5;
        if v_status not in ('OPEN','PARTIAL') then raise_application_error(-20401, 'TITLE_NOT_SETTLEABLE'); end if;
        if p_principal > v_open then raise_application_error(-20402, 'INVALID_SETTLEMENT_AMOUNT'); end if;
        insert into mc_settlement(title_id, idempotency_key, principal_amount, interest_amount, penalty_amount, discount_amount)
        values (p_title_id, p_idempotency_key, p_principal, nvl(p_interest,0), nvl(p_penalty,0), nvl(p_discount,0))
        returning settlement_id into v_settlement_id;
        update mc_financial_title set open_amount = open_amount - p_principal,
            status = case when open_amount - p_principal = 0 then 'SETTLED' else 'PARTIAL' end,
            record_version = record_version + 1 where title_id = p_title_id;
        pkg_audit.record_event(p_actor, 'TITLE_SETTLED', 'FINANCIAL_TITLE', to_char(p_title_id), p_correlation_id, null,
            json_object('settlementId' value v_settlement_id, 'principal' value p_principal, 'interest' value nvl(p_interest,0), 'penalty' value nvl(p_penalty,0), 'discount' value nvl(p_discount,0)));
    exception
        when dup_val_on_index then raise_application_error(-20403, 'DUPLICATE_SETTLEMENT');
        when no_data_found then raise_application_error(-20407, 'FINANCIAL_TITLE_NOT_FOUND');
        when e_resource_busy then raise_application_error(-20408, 'FINANCIAL_TITLE_LOCKED');
        when e_wait_timeout then raise_application_error(-20408, 'FINANCIAL_TITLE_LOCKED');
    end;

    procedure cancel_title(p_title_id number, p_reason varchar2, p_actor varchar2, p_correlation_id varchar2) is
        v_status mc_financial_title.status%type;
    begin
        if trim(p_reason) is null then raise_application_error(-20409, 'CANCELLATION_REASON_REQUIRED'); end if;
        assert_open_period(trunc(sysdate));
        select status into v_status from mc_financial_title where title_id = p_title_id for update wait 5;
        if v_status <> 'OPEN' then raise_application_error(-20410, 'TITLE_NOT_CANCELLABLE'); end if;
        update mc_financial_title set status = 'CANCELLED', open_amount = 0, record_version = record_version + 1 where title_id = p_title_id;
        pkg_audit.record_event(p_actor, 'TITLE_CANCELLED', 'FINANCIAL_TITLE', to_char(p_title_id), p_correlation_id, null, json_object('reason' value p_reason));
    exception
        when no_data_found then raise_application_error(-20407, 'FINANCIAL_TITLE_NOT_FOUND');
    end;

    procedure reverse_settlement(p_settlement_id number, p_idempotency_key varchar2, p_actor varchar2, p_correlation_id varchar2, p_reversal_id out number) is
        v_settlement mc_settlement%rowtype;
        v_title mc_financial_title%rowtype;
    begin
        if p_idempotency_key is null then raise_application_error(-20411, 'REVERSAL_IDEMPOTENCY_REQUIRED'); end if;
        assert_open_period(trunc(sysdate));
        select * into v_settlement from mc_settlement where settlement_id = p_settlement_id for update wait 5;
        if v_settlement.status <> 'CONFIRMED' then raise_application_error(-20412, 'SETTLEMENT_NOT_REVERSIBLE'); end if;
        select * into v_title from mc_financial_title where title_id = v_settlement.title_id for update wait 5;
        insert into mc_settlement(title_id, idempotency_key, principal_amount, interest_amount, penalty_amount, discount_amount, status, reversal_id)
        values (v_settlement.title_id, p_idempotency_key, v_settlement.principal_amount, v_settlement.interest_amount, v_settlement.penalty_amount, v_settlement.discount_amount, 'REVERSED', p_settlement_id)
        returning settlement_id into p_reversal_id;
        update mc_settlement set status = 'REVERSED', reversal_id = p_reversal_id where settlement_id = p_settlement_id;
        update mc_financial_title set open_amount = open_amount + v_settlement.principal_amount,
            status = case when open_amount + v_settlement.principal_amount = original_amount then 'OPEN' else 'PARTIAL' end,
            record_version = record_version + 1 where title_id = v_settlement.title_id;
        pkg_audit.record_event(p_actor, 'SETTLEMENT_REVERSED', 'FINANCIAL_TITLE', to_char(v_settlement.title_id), p_correlation_id, null,
            json_object('settlementId' value p_settlement_id, 'reversalId' value p_reversal_id, 'principal' value v_settlement.principal_amount));
    exception
        when dup_val_on_index then raise_application_error(-20413, 'DUPLICATE_REVERSAL');
        when no_data_found then raise_application_error(-20414, 'SETTLEMENT_NOT_FOUND');
    end;
end pkg_financial;
/

create or replace package pkg_reporting as
    function expiring_lots(p_days number default 60) return tt_expiry_alert pipelined;
    procedure open_report(p_report_name varchar2, p_unit_id number, p_result out sys_refcursor);
    procedure refresh_analytics(p_actor varchar2 default 'SCHEDULER');
end pkg_reporting;
/

create or replace package body pkg_reporting as
    function expiring_lots(p_days number default 60) return tt_expiry_alert pipelined is
    begin
        for r in (select product_id, unit_id, lot_id, lot_code, expires_on, quantity from mc_inventory_lot where expires_on between trunc(sysdate) and trunc(sysdate) + p_days and quantity > 0 order by expires_on) loop
            pipe row(ty_expiry_alert(r.product_id, r.unit_id, r.lot_id, r.lot_code, r.expires_on, r.quantity));
        end loop;
        return;
    end;

    procedure open_report(p_report_name varchar2, p_unit_id number, p_result out sys_refcursor) is
        v_sql varchar2(4000);
    begin
        if p_report_name = 'FINANCIAL_AGING' then
            v_sql := 'select title_type, aging_bucket, title_count, open_amount from vw_mc_financial_aging where unit_id = :unit_id order by title_type, aging_bucket';
        elsif p_report_name = 'BED_OCCUPANCY' then
            v_sql := 'select unit_code, bed_code, bed_status, admission_id, started_at from vw_mc_bed_occupancy where unit_code = (select code from mc_business_unit where unit_id = :unit_id) order by bed_code';
        else
            raise_application_error(-20601, 'REPORT_NOT_ALLOWED');
        end if;
        open p_result for v_sql using p_unit_id;
    end;

    procedure refresh_analytics(p_actor varchar2 default 'SCHEDULER') is
        pragma autonomous_transaction;
        v_refresh_id number;
        v_error_code number;
        v_error_message varchar2(500);
        v_row_count number;
    begin
        insert into mc_analytics_refresh_log(materialized_view_name, started_at, status, refreshed_by)
        values ('MV_MC_EXECUTIVE_KPI', systimestamp, 'RUNNING', nvl(p_actor, 'SCHEDULER')) returning refresh_id into v_refresh_id;
        commit;
        begin
            dbms_mview.refresh('MV_MC_EXECUTIVE_KPI', method => 'C', atomic_refresh => false);
            select count(*) into v_row_count from mv_mc_executive_kpi;
            update mc_analytics_refresh_log set finished_at = systimestamp, status = 'SUCCESS', row_count = v_row_count where refresh_id = v_refresh_id;
            commit;
        exception
            when others then
                v_error_code := sqlcode;
                v_error_message := substr(sqlerrm, 1, 500);
                update mc_analytics_refresh_log set finished_at = systimestamp, status = 'ERROR', error_code = v_error_code, error_message = v_error_message where refresh_id = v_refresh_id;
                commit;
                raise;
        end;
    end;
end pkg_reporting;
/

begin
    dbms_scheduler.set_attribute('JOB_MC_REFRESH_ANALYTICS', 'job_action', 'begin pkg_reporting.refresh_analytics(''SCHEDULER''); end;');
end;
/

create or replace view vw_mc_analytics_refresh_status as
select materialized_view_name, started_at, finished_at, status, refreshed_by, error_code, error_message, row_count,
       row_number() over(partition by materialized_view_name order by started_at desc, refresh_id desc) refresh_rank
  from mc_analytics_refresh_log;
